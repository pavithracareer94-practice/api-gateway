package com.example.security;

import io.jsonwebtoken.Claims;
import io.jsonwebtoken.Jwts;
import io.jsonwebtoken.security.Keys;
import org.springframework.stereotype.Component;

import javax.crypto.SecretKey;
import java.nio.charset.StandardCharsets;
import java.util.Base64;
import java.util.Date;

@Component
public class JwtUtil {

    // Must be at least 32 characters (256 bits) for HMAC-SHA256
    private static final String SECRET = "MySuperSecretKeyForJwtSigningInMicroservices2026!";
    private static final long EXPIRATION_MS = 1000 * 60 * 60; // 1 hour

    private SecretKey getSigningKey() {

        return Keys.hmacShaKeyFor(SECRET.getBytes(StandardCharsets.UTF_8));
    }

    /*
    Signature (zzzzz)The signature contains no readable JSON data.
    Instead, it is a raw cryptographic byte array that has been
    Base64URL-encoded.It is generated by taking the encoded header,
    adding a dot (.), adding the encoded payload, and signing that combined string
    using your secret key and algorithm
    	"Signature"="HMAC-SHA256" ("base64UrlEncode(header)"
    	+\".\"+"base64UrlEncode(payload)" ,"SECRET" )
    When an incoming request hits your API Gateway,
    the parser recomputes this signature using the incoming header, payload, and
    your local secret.
    If the recomputed signature matches the zzzzz string perfectly,
    the gateway knows the token is authentic and hasn't been tampered with.
     */
    public String generateToken(String username) {
        String token = Jwts.builder()
                .subject(username)
                .issuedAt(new Date())
                .expiration(new Date(System.currentTimeMillis() + EXPIRATION_MS))
                .signWith(getSigningKey())
                .compact();

       // printDecodedToken(token);
        return token;
    }

    public String validateAndExtractUsername(String token) {
        Claims claims = Jwts.parser()
                .verifyWith(getSigningKey())
                .build()
                .parseSignedClaims(token)
                .getPayload();
        return claims.getSubject();
    }

    public void printDecodedToken(String token) {
        String[] parts = token.split("\\.");

        if (parts.length == 3) {
            String header = new String(Base64.getUrlDecoder().decode(parts[0]), StandardCharsets.UTF_8);
            String payload = new String(Base64.getUrlDecoder().decode(parts[1]), StandardCharsets.UTF_8);

            System.out.println("=====================");
            System.out.println("Token :: "+ token);
            System.out.println("=== JWT BREAKDOWN ===");
            System.out.println("1. Header    : " + header);
            System.out.println("2. Payload   : " + payload);
            System.out.println("3. Signature : " + parts[2] + " (Base64URL-encoded HMAC-SHA256 bytes)");
            System.out.println("=====================");
        }
    }
}